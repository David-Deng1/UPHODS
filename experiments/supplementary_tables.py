"""Supplementary Tables S1 and S2 from results/final/tableS1_per_instance.csv.

    uv run python experiments/supplementary_tables.py results/final > results/final/supplementary_tables.md

S1: median and interquartile range of the final error, S2: mean and standard
deviation, for the 11 methods on all 36 instances (30 runs each).  All values
in the same scientific notation (Reviewer 2, comment on AIP).  The lowest
median (S1) and the lowest mean (S2) per instance are marked in bold.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.stdout.reconfigure(encoding="utf-8")
R = Path(sys.argv[1])
S = pd.read_csv(R / "tableS1_per_instance.csv")
ORDER = [
    "UPHODS",
    "SW-UCB",
    "FSS-1",
    "FSS-2",
    "FSS-3",
    "FSS-4",
    "GP-PO",
    "GA",
    "PSO",
    "SA",
    "GD",
]
FUNCS = [
    "Ackley",
    "Griewank",
    "Rastrigin",
    "Rosenbrock",
    "ShiftedRastrigin",
    "ShiftedSphere",
]
LABEL = {"ShiftedRastrigin": "Shifted Rastrigin", "ShiftedSphere": "Shifted Sphere"}
DIMS = sorted(S.dim.unique())


def sci(v):
    return "0" if v == 0 else f"{v:.2e}"


def table(kind):
    for fn in FUNCS:
        sub = S[S.function == fn]
        print(f"\n**{LABEL.get(fn, fn)}**\n")
        print("| Method | " + " | ".join(f"D = {d}" for d in DIMS) + " |")
        print("|---|" + "---|" * len(DIMS))
        best = {d: sub[sub.dim == d][kind[0]].min() for d in DIMS}
        for m in ORDER:
            cells = []
            for d in DIMS:
                r = sub[(sub.dim == d) & (sub.method == m)].iloc[0]
                if kind[0] == "median":
                    c = f"{sci(r['median'])} [{sci(r.q1)}, {sci(r.q3)}]"
                else:
                    c = f"{sci(r['mean'])} ± {sci(r.sd)}"
                cells.append(f"**{c}**" if r[kind[0]] == best[d] else c)
            print(f"| {m} | " + " | ".join(cells) + " |")


print(
    "# Supplementary tables (generated by experiments/supplementary_tables.py; seeds 0-29)"
)
print(
    "\n## Table S1. Final error: median [first quartile, third quartile] over 30 runs\n"
)
print("Errors below 1e-8 are set to 0. Bold: lowest median on the instance.")
table(("median",))
print("\n## Table S2. Final error: mean ± standard deviation over 30 runs\n")
print("Errors below 1e-8 are set to 0. Bold: lowest mean on the instance.")
table(("mean",))
print("\n## Table S3. Mean number of switches per run (hybrid methods)\n")
print("| Function | D | " + " | ".join(m for m in ORDER[:7]) + " |")
print("|---|---|" + "---|" * 7)
for fn in FUNCS:
    for d in DIMS:
        sub = S[(S.function == fn) & (S.dim == d)].set_index("method")
        print(
            f"| {LABEL.get(fn, fn)} | {d} | "
            + " | ".join(f"{sub.loc[m, 'ns']:.1f}" for m in ORDER[:7])
            + " |"
        )
